/**
 * A demo adapter for the quality and audio-track stories: it plays the file natively and reports
 * renditions and audio tracks the way an adaptive streaming adapter would.
 */
class DemoRenditionsAdapter implements AndesMediaAdapter {
  readonly name = 'demo-renditions';
  private hooks: AndesMediaAdapterHooks | null = null;
  private media: HTMLMediaElement | null = null;

  canPlay(source: AndesMediaSource): boolean {
    return source.src.endsWith('.mp4');
  }

  attach(
    media: HTMLMediaElement,
    source: AndesMediaSource,
    hooks: AndesMediaAdapterHooks,
  ): void {
    this.media = media;
    this.hooks = hooks;
    media.src = source.src;
    hooks.setQualities([
      { id: '1080', height: 1080, bitrate: 6_000_000 },
      { id: '720', height: 720, bitrate: 3_000_000 },
      { id: '480', height: 480, bitrate: 1_200_000 },
      { id: '240', height: 240, bitrate: 400_000 },
    ]);
    hooks.setActiveQuality('720', true);
    hooks.setAudioTracks([
      { id: 'en', label: 'English', language: 'en' },
      { id: 'es', label: 'Español', language: 'es' },
      { id: 'commentary', label: 'Commentary', language: 'en' },
    ]);
    hooks.setActiveAudioTrack('en');
  }

  selectQuality(id: string): void {
    this.hooks?.setActiveQuality(id === 'auto' ? '720' : id, id === 'auto');
  }

  selectAudioTrack(id: string): void {
    this.hooks?.setActiveAudioTrack(id);
  }

  detach(): void {
    this.media?.removeAttribute('src');
    this.media = null;
    this.hooks = null;
  }
}

/**
 * A demo live adapter: it reports a live stream with a DVR window over the short sample file and
 * keeps "live" playback near the edge by wrapping around before the file ends.
 */
class DemoLiveAdapter implements AndesMediaAdapter {
  readonly name = 'demo-live';
  private media: HTMLMediaElement | null = null;
  /** Whether the viewer moved away from the edge (then playback runs on normally). */
  private behind = false;
  private internalSeek = false;
  private readonly onTimeUpdate = () => {
    const media = this.media;
    if (media && !this.behind && media.duration - media.currentTime < 0.6) {
      this.internalSeek = true;
      media.currentTime = media.duration - 2;
    }
  };
  private readonly onSeeking = () => {
    const media = this.media;
    if (media && !this.internalSeek) {
      this.behind = media.duration - media.currentTime > 2.5;
    }
    this.internalSeek = false;
  };

  constructor(private readonly dvr: boolean) {}

  canPlay(): boolean {
    return true;
  }

  attach(
    media: HTMLMediaElement,
    source: AndesMediaSource,
    hooks: AndesMediaAdapterHooks,
  ): void {
    this.media = media;
    media.src = source.src;
    media.addEventListener('timeupdate', this.onTimeUpdate);
    media.addEventListener('seeking', this.onSeeking);
    media.addEventListener(
      'loadedmetadata',
      () => {
        this.internalSeek = true;
        media.currentTime = media.duration - 2;
        hooks.setLive({
          streamType: this.dvr ? 'live-dvr' : 'live',
          liveEdge: media.duration,
          liveEdgeTolerance: 2.5,
        });
      },
      { once: true },
    );
  }

  detach(): void {
    this.media?.removeEventListener('timeupdate', this.onTimeUpdate);
    this.media?.removeEventListener('seeking', this.onSeeking);
    this.media?.removeAttribute('src');
    this.media = null;
  }
}

