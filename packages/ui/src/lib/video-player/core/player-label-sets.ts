/**
 * A count with its word, choosing the singular only for exactly one (or below two where the
 * language counts zero as singular). Plain functions instead of a plural engine: the player
 * only ever counts hours, minutes and seconds.
 */
function count(
  value: number,
  one: string,
  other: string,
  zeroIsSingular = false,
): string {
  const singular = value === 1 || (zeroIsSingular && value === 0);
  return `${value} ${singular ? one : other}`;
}

