/** The built-in label sets by primary language subtag. */
export const ANDES_PLAYER_LABEL_SETS: Readonly<
  Record<'en' | 'es' | 'pt' | 'fr' | 'de' | 'it', AndesPlayerLabels>
> = {
  en: ANDES_PLAYER_DEFAULT_LABELS,
  es: ANDES_PLAYER_LABELS_ES,
  pt: ANDES_PLAYER_LABELS_PT,
  fr: ANDES_PLAYER_LABELS_FR,
  de: ANDES_PLAYER_LABELS_DE,
  it: ANDES_PLAYER_LABELS_IT,
};

/**
 * The built-in labels for a BCP 47 tag (`es-PE` uses Spanish), or English when the language
 * has no built-in set.
 */
export function andesPlayerLabelsFor(locale: string): AndesPlayerLabels {
  const language = locale.toLowerCase().split(/[-_]/)[0];
  return (
    ANDES_PLAYER_LABEL_SETS[language as keyof typeof ANDES_PLAYER_LABEL_SETS] ??
    ANDES_PLAYER_DEFAULT_LABELS
  );
}

/**
 * Provides a built-in label set for every player below this injector, with optional overrides
 * on top: `provideAndesPlayerLocale('es')`, or `provideAndesPlayerLocale(LOCALE_ID_VALUE)`.
 */
export function provideAndesPlayerLocale(
  locale: string,
  overrides: AndesPlayerLabelOverrides = {},
): Provider {
  return provideAndesPlayerLabels(
    mergeAndesPlayerLabels(andesPlayerLabelsFor(locale), overrides),
  );
}
